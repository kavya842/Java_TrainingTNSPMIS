//! What is wrapper class
// java has eight primitive data types wrapper classes represent their values as objects.
  // primitive           Wrapper class
    //   byte                Byte
    //   short               Short
    //   int                  Int
    //   long                Long
    // float                  Float
    // double                Double
    // char                    Char
    // boolean               Boolean
//! Why do we need wrappers?
// 1. Collections such as ArrayList store objects, not primitive types.
// 2. A wrapper reference can be null to represent a missing value.
// 3. Wrapper classes provide helpful methods for parsing, conversion and comparison.
// 4. They provide constants such as Integer.MAX_VALUE